const porSlug = new Map<MateriaSlug, Materia>(MATERIAS.map((m) => [m.slug, m]));

export function getMateria(slug: MateriaSlug): Materia {
  const materia = porSlug.get(slug);
  if (!materia) throw new Error(`Matéria desconhecida: ${slug}`);
  return materia;
}

export function isMateriaSlug(valor: string): valor is MateriaSlug {
  return porSlug.has(valor as MateriaSlug);
}
